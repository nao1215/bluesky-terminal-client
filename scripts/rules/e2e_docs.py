#!/usr/bin/env python3
"""Generate atago's spec pages and compare their complete tree with doc/e2e."""
import argparse
from pathlib import Path
import shutil
import subprocess
import tempfile

import docs

ROOT = Path(__file__).resolve().parents[2]
CLIENTS = {"bsky": "bluesky", "msky": "misskey", "mstdn": "mastodon", "nstr": "nostr"}


def generate(destination):
    index = ["# E2E scenarios", "", "These pages are generated by atago v0.28.0 from the committed specs; they describe assertions, not passing server results. Mock suites use local stand-ins. Compatibility suites use disposable loopback servers. See [compatibility results](../compat.md) for versions, dates, timings and coverage limits.", "", "Run `just e2e-docs` to regenerate every page. Fixture strings in the generated pages retain the specs' literal test data.", "", "| Client | Mock suite | Live compatibility suite |", "| --- | --- | --- |"]
    for client, crate in CLIENTS.items():
        for kind, source in (("mock", "atago"), ("compat", "compat")):
            specs = Path(f"crates/{crate}-terminal-client/e2e/{source}")
            if not (ROOT / specs).is_dir():
                continue
            out = destination / client / kind
            subprocess.run(["atago", "doc", "--split-by-spec", "--out-dir", str(out), str(specs)], cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
            # atago supplies all content; only its heading/list separators are
            # adapted to the repository's prose style. Test literals stay intact.
            for page in out.glob("*.md"):
                lines, formatted, fence, previous = page.read_text().splitlines(), [], False, False
                for line in lines:
                    if line.startswith("```"):
                        formatted.extend([line, ""] if fence else ["", line])
                        fence = not fence
                        previous = False
                        continue
                    if not fence:
                        if line.startswith(("#", "- [")):
                            line = line.replace(" — ", ": ")
                        paragraph = bool(line.strip()) and not docs.is_block_line(line)
                        if previous and paragraph:
                            formatted.append("")
                        previous = paragraph
                    formatted.append(line)
                page.write_text("\n".join(formatted) + "\n")
        live = "Not present" if client == "bsky" else f"[Scenarios]({client}/compat/index.md)"
        index.append(f"| {client} | [Scenarios]({client}/mock/index.md) | {live} |")
    (destination / "README.md").write_text("\n".join(index) + "\n")


def tree(directory):
    return {p.relative_to(directory): p.read_bytes() for p in directory.rglob("*") if p.is_file()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--update", action="store_true")
    args = parser.parse_args()
    try:
        version = subprocess.check_output(["atago", "version"], text=True).strip()
    except FileNotFoundError:
        parser.exit(1, "e2e-docs: install atago v0.28.0, then run just e2e-docs\n")
    if version != "atago v0.28.0":
        parser.exit(1, f"e2e-docs: expected atago v0.28.0, found {version}; install the CI version\n")
    committed = ROOT / "doc/e2e"
    with tempfile.TemporaryDirectory(prefix="stc-e2e-docs-") as temporary:
        generated = Path(temporary)
        generate(generated)
        if args.update:
            if committed.exists():
                shutil.rmtree(committed)
            shutil.copytree(generated, committed)
            return 0
        expected, actual = tree(generated), tree(committed)
        changed = sorted(str(p) for p in expected.keys() | actual.keys() if expected.get(p) != actual.get(p))
        if changed:
            parser.exit(1, "e2e-docs: drift in " + ", ".join(changed) + "; run just e2e-docs\n")
    print("e2e-docs: generated pages are in sync")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
